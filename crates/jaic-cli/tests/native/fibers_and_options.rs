/// Compiler atomic intrinsics reach LLVM with the order the program names, and
/// the program gives the same answers as the interpreter.
#[test]
fn ordered_atomics_keep_their_memory_orders() {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("atomics-ordered");
    std::fs::create_dir_all(&dir).unwrap();
    let source = dir.join("ordered.jai");
    std::fs::write(
        &source,
        "#import \"Basic\";\n\
         atomic_store_order :: (p: *u32, value: u32, order: s64) #intrinsic #no_context;\n\
         atomic_load_order :: (p: *u32, order: s64) -> u32 #intrinsic #no_context;\n\
         atomic_fetch_add_order :: (p: *u32, value: u32, order: s64) -> u32 #intrinsic #no_context;\n\
         atomic_exchange_order :: (p: *u32, value: u32, order: s64) -> u32 #intrinsic #no_context;\n\
         atomic_compare_exchange_order :: (p: *u32, expected: u32, value: u32, orders: s64) -> bool, u32 #intrinsic #no_context;\n\
         main :: () {\n\
             x: u32;\n\
             atomic_store_order(*x, 1, 2);\n\
             a := atomic_load_order(*x, 1);\n\
             b := atomic_fetch_add_order(*x, 2, 0);\n\
             c := atomic_exchange_order(*x, 7, 3);\n\
             ok, d := atomic_compare_exchange_order(*x, 7, 9, 2);\n\
             print(\"% % % % %\\n\", a, b, c, ok, d);\n\
         }\n",
    )
    .unwrap();
    let interpreted = jaic()
        .arg("-interp")
        .arg(&source)
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        interpreted.status.success(),
        "{}",
        String::from_utf8_lossy(&interpreted.stderr)
    );
    assert_eq!(interpreted.stdout, b"1 1 3 true 7\n");
    let ir = dir.join("ordered.ll");
    let exe = exe_path(&dir, "ordered");
    let build = jaic()
        .arg(&source)
        .arg("-O0")
        .arg("-exe")
        .arg(&exe)
        .arg("-emit_ir")
        .arg(&ir)
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        build.status.success(),
        "{}",
        String::from_utf8_lossy(&build.stderr)
    );
    let ir = read_ir_parts(&ir);
    for expected in [
        "store atomic i32 1, ptr",
        " release, align 4",
        "load atomic i32, ptr %",
        " acquire, align 4",
        "atomicrmw add ptr",
        " monotonic, align 4",
        "atomicrmw xchg ptr",
        " acq_rel, align 4",
        "cmpxchg ptr",
        " release monotonic, align 4",
    ] {
        assert!(ir.contains(expected), "missing `{expected}` in:\n{ir}");
    }
    let run = Command::new(&exe).output().unwrap();
    assert!(run.status.success());
    assert_eq!(run.stdout, interpreted.stdout);
}

/// `-exe` and `-output_path` place the executable: a bare name goes in the directory jaic was
/// started in, like a name with a directory, and `-output_path` holds either.
#[test]
fn exe_and_output_path_place_the_executable() {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("native-exe-output");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(
        dir.join("src/prog.jai"),
        "#import \"Basic\";\nmain :: () { print(\"placed\\n\"); }\n",
    )
    .unwrap();
    let build = |extra: &[&str]| {
        let output = jaic()
            .arg("src/prog.jai")
            .args(extra)
            .current_dir(&dir)
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{extra:?}: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    };
    build(&[]);
    build(&["-exe", "renamed"]);
    build(&["-exe", "bin/app.out"]);
    build(&["-output_path", "out", "-exe", "named"]);
    build(&["-output_path", "out2"]);
    build(&["-output_path", "out3", "-exe", "sub/deep.bin"]);
    let expected = [
        exe_path(&dir.join("src"), "prog"),
        exe_path(&dir, "renamed"),
        dir.join("bin/app.out"),
        exe_path(&dir.join("out"), "named"),
        exe_path(&dir.join("out2"), "prog"),
        dir.join("out3/sub/deep.bin"),
    ];
    for path in &expected {
        assert!(path.is_file(), "{} was not written", path.display());
    }
    let run = Command::new(&expected[2]).output().unwrap();
    assert_eq!(String::from_utf8_lossy(&run.stdout), "placed\n");
}

/// `-o` builds optimized without stack traces or runtime checks, `-od` keeps both, and
/// `-no_inline` and `-no_split` leave the program's behavior alone.
#[test]
fn optimization_flavors_build_and_run() {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("native-flavors");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let source = dir.join("flavors.jai");
    std::fs::write(
        &source,
        "#import \"Basic\";\n\
         add :: (a: int, b: int) -> int { return a + b; }\n\
         main :: () {\n\
         \x20   a: [3] int;\n\
         \x20   index := 2 + add(0, 0);\n\
         \x20   print(\"%\\n\", a[index]);\n\
         }\n",
    )
    .unwrap();
    for flags in [
        &["-o"][..],
        &["-optimized"],
        &["-od"],
        &["-very_debug"],
        &["-o", "-no_inline", "-no_split"],
        &["-O1", "-no_split"],
    ] {
        let name = format!("flavor{}", flags.join(""));
        let exe = exe_path(&dir, &name);
        let build = jaic()
            .arg(&source)
            .args(flags)
            .arg("-exe")
            .arg(&exe)
            .output()
            .unwrap();
        assert!(
            build.status.success(),
            "{flags:?}: {}",
            String::from_utf8_lossy(&build.stderr)
        );
        let run = Command::new(&exe).output().unwrap();
        // Index 2 of 3 is in range under every flavor.
        assert!(run.status.success(), "{flags:?}");
        assert_eq!(String::from_utf8_lossy(&run.stdout), "0\n", "{flags:?}");
    }
}

/// `-add` and `-run` reach a metaprogram-free build too, and `-no_check_bindings` is accepted
/// without a Check plugin.
#[test]
fn add_and_run_strings_in_a_build() {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("native-add-run");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let source = dir.join("added.jai");
    std::fs::write(
        &source,
        "#import \"Basic\";\nmain :: () { print(\"%\\n\", added); }\n",
    )
    .unwrap();
    let exe = exe_path(&dir, "added");
    let build = jaic()
        .arg(&source)
        .args(["-add", "added :: 41 + 1;", "-run", "print(\"compiled\\n\")"])
        .args(["-no_check_bindings", "-no_check", "-exe"])
        .arg(&exe)
        .output()
        .unwrap();
    assert!(
        build.status.success(),
        "{}",
        String::from_utf8_lossy(&build.stderr)
    );
    assert_eq!(String::from_utf8_lossy(&build.stdout), "compiled\n");
    let run = Command::new(&exe).output().unwrap();
    assert_eq!(String::from_utf8_lossy(&run.stdout), "42\n");
}

/// A compile-time call into a library that cannot be found names the library, not only the symbol.
#[test]
fn compile_time_call_into_a_missing_library_names_it() {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("native-missing-library");
    std::fs::create_dir_all(&dir).unwrap();
    let source = dir.join("missing.jai");
    std::fs::write(
        &source,
        "missing :: #foreign_library \"jaic_no_such_library\";\nanswer :: () -> s32 #foreign missing;\n#run answer();\nmain :: () {}\n",
    )
    .unwrap();
    let output = jaic()
        .arg(&source)
        .arg("-check")
        .env("JAIC_NATIVE_LIBS", &dir)
        .output()
        .unwrap();
    assert!(!output.status.success());
    let stderr = String::from_utf8_lossy(&output.stderr);
    // Windows reports the library while loading it, other hosts when the call is resolved.
    assert!(
        stderr.contains("library `jaic_no_such_library`"),
        "{stderr}"
    );
}
