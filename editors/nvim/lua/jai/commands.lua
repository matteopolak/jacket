---The `:Jai <subcommand>` command.
local config = require('jai.config')
local format = require('jai.format')
local jai = require('jai')
local toolchain = require('jai.toolchain')

local M = {}

---@param msg string
---@param level? integer
local function notify(msg, level)
  vim.notify('Jai: ' .. msg, level or vim.log.levels.INFO)
end

---@return vim.lsp.Client?
local function server(bufnr)
  local client = vim.lsp.get_clients({ bufnr = bufnr or 0, name = jai.SERVER })[1]
  if not client then
    notify('the language server is not running for this buffer (:checkhealth jai)', vim.log.levels.WARN)
  end
  return client
end

---The quickfix items in `jailint` output: a `level[rule]: message` line, then ` --> file:line:col`.
---@param output string
---@return vim.quickfix.entry[]
function M.parse_jailint(output)
  local items, header = {}, nil
  for line in output:gmatch('[^\r\n]+') do
    local level, rule, text = line:match('^(%a+)%[([%w_]+)%]: (.*)$')
    if level then
      header = { type = level == 'error' and 'E' or 'W', text = ('%s: %s'):format(rule, text) }
    else
      local file, lnum, col = line:match('^%s*%-%->%s+(.-):(%d+):(%d+)%s*$')
      if file and header then
        items[#items + 1] = { filename = file, lnum = tonumber(lnum), col = tonumber(col), type = header.type, text = header.text }
        header = nil
      end
    end
  end
  return items
end

---Lint the project (the folder with `jai.toml`, `jailint.toml` or `.git`) into the quickfix list.
local function lint()
  local linter = toolchain.find('jailint')
  if not linter then
    return notify('jailint was not found: put it on PATH or run :Jai install', vim.log.levels.WARN)
  end
  local root = vim.fs.root(0, { 'jai.toml', 'jailint.toml', '.git' }) or vim.uv.cwd() --[[@as string]]
  notify('linting ' .. root)
  vim.system({ linter.path, '--color', 'never', root }, { cwd = root, text = true, env = config.tool_env() }, vim.schedule_wrap(function(out)
    -- Exit 1 means findings at level deny; 2 a usage or configuration error.
    if out.code == 2 or out.code == 127 then
      return notify('jailint failed: ' .. vim.trim(out.stderr or ''), vim.log.levels.ERROR)
    end
    local items = M.parse_jailint(out.stderr .. '\n' .. out.stdout)
    for _, item in ipairs(items) do
      item.filename = vim.fs.normalize(vim.fs.joinpath(root, item.filename))
    end
    vim.fn.setqflist({}, ' ', { title = 'jailint', items = items })
    if #items > 0 then
      vim.cmd('botright copen')
    else
      notify('no findings')
    end
  end))
end

---Apply jailint's safe fixes to the buffer through the server's `source.fixAll.jailint` action.
local function fix()
  if server() then
    vim.lsp.buf.code_action({ context = { only = { 'source.fixAll.jailint' }, diagnostics = {} }, apply = true })
  end
end

---Show the code generated by the `#insert`, `#run`, `#if` or macro call under the cursor.
local function expand()
  local client = server()
  if not client then
    return
  end
  local params = vim.lsp.util.make_position_params(0, client.offset_encoding)
  client:request('jai/expansion', params, function(err, result)
    if err then
      return notify(err.message, vim.log.levels.ERROR)
    end
    if not result then
      return notify('there is no expansion here')
    end
    local buf = vim.api.nvim_create_buf(false, true)
    vim.bo[buf].buftype = 'nofile'
    vim.bo[buf].bufhidden = 'wipe'
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, vim.split(result.text, '\n', { plain = true }))
    vim.bo[buf].filetype = 'jai'
    vim.bo[buf].modifiable = false
    vim.api.nvim_buf_set_name(buf, 'jai-expansion://' .. (result.kind or 'expansion') .. '/' .. buf)
    vim.cmd('vsplit')
    vim.api.nvim_win_set_buf(0, buf)
  end)
end

---List the instances a polymorphic procedure has been instantiated with.
local function polymorphs()
  local client = server()
  if not client then
    return
  end
  local position = vim.lsp.util.make_position_params(0, client.offset_encoding).position
  -- The commands take a `{ uri, position }` argument, not a text document identifier.
  local target = { uri = vim.uri_from_bufnr(0), position = position }
  client:exec_cmd({ title = 'Polymorphs', command = 'jai.showPolymorphs', arguments = { target } }, { bufnr = 0 }, function(err, result)
    if err then
      return notify(err.message, vim.log.levels.ERROR)
    end
    if type(result) ~= 'table' or #result == 0 then
      return notify('nothing has instantiated this procedure yet')
    end
    vim.ui.select(result, { prompt = ('%d polymorph instances'):format(#result) }, function() end)
  end)
end

---`jaic <command> <file>` in a terminal split.
---@param command 'run'|'build'|'check'
local function compile(command)
  local file = vim.api.nvim_buf_get_name(0)
  if vim.bo.filetype ~= 'jai' or file == '' then
    return notify('open a saved .jai file first', vim.log.levels.WARN)
  end
  local compiler = toolchain.find('jaic')
  if not compiler then
    return notify('jaic was not found: set compiler.path, put jaic on PATH, or run :Jai install', vim.log.levels.WARN)
  end
  vim.cmd('silent update')
  local cmd = vim.list_extend({ compiler.path, command, file }, config.get().run.arguments)
  vim.cmd('botright 15split')
  vim.fn.jobstart(cmd, { term = true, cwd = vim.fs.dirname(file), env = config.tool_env() })
end

---@type table<string, fun()>
local subcommands = {
  install = function()
    jai.install()
  end,
  update = function()
    jai.install()
  end,
  restart = function()
    jai.restart(function()
      notify('restarted jailsp')
    end)
  end,
  fix = fix,
  lint = lint,
  format = function()
    local changed, err = format.format(0)
    if err then
      notify(err, vim.log.levels.WARN)
    elseif not changed then
      notify('already formatted')
    end
  end,
  expand = expand,
  polymorphs = polymorphs,
  run = function()
    compile('run')
  end,
  build = function()
    compile('build')
  end,
  check = function()
    compile('check')
  end,
  health = function()
    vim.cmd('checkhealth jai')
  end,
}

---@return string[]
function M.names()
  local names = vim.tbl_keys(subcommands)
  table.sort(names)
  return names
end

---@param opts { args: string }
function M.run(opts)
  local name = vim.trim(opts.args)
  local fn = subcommands[name]
  if not fn then
    return notify(('unknown subcommand %q; one of: %s'):format(name, table.concat(M.names(), ', ')), vim.log.levels.ERROR)
  end
  fn()
end

---@param lead string
---@return string[]
function M.complete(lead)
  return vim.tbl_filter(function(name)
    return vim.startswith(name, lead)
  end, M.names())
end

return M
