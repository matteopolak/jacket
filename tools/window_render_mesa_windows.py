#!/usr/bin/env python3
"""Build a real native ARM64 Mesa WGL/llvmpipe driver from pinned upstream sources.

Run inside a native ARM64 VS2022 developer environment. --plan works on any OS
and records configuration only; it never means the driver built or executed.
"""
import argparse
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import tarfile
import urllib.request

from window_render_wgl_ci import pe_machine

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "mesa": (
        "https://archive.mesa3d.org/mesa-25.2.5.tar.xz",
        "bb6243e7a6f525febfa1e6ab50827ca4d4bfdad73812377b0ca9b6c50998b03e",
        "mesa-25.2.5"),
    "llvm": (
        "https://github.com/llvm/llvm-project/releases/download/llvmorg-20.1.8/llvm-project-20.1.8.src.tar.xz",
        "6898f963c8e938981e6c4a302e83ec5beb4630147c7311183cf61069af16333d",
        "llvm-project-20.1.8.src"),
    "winflexbison": (
        "https://codeload.github.com/lexxmark/winflexbison/tar.gz/1176da2adaf972b2216b1ac8dd611e128fe80bc5",
        "94f24390699474cd0448be9f144652e8127690c5eda5aeef32cd3f563a6705bc",
        "winflexbison-1176da2adaf972b2216b1ac8dd611e128fe80bc5"),
}
PACKAGES = {"cmake": "3.31.6", "ninja": "1.13.2", "meson": "1.8.3",
            "Mako": "1.3.10", "MarkupSafe": "3.0.3", "packaging": "25.0", "PyYAML": "6.0.3"}
MESA_OPTIONS = ["--buildtype=release", "--wrap-mode=nofallback", "-Db_vscrt=mt",
                "-Dgallium-drivers=llvmpipe", "-Dvulkan-drivers=[]", "-Dplatforms=[]",
                "-Dllvm=enabled", "-Dshared-llvm=disabled", "-Ddraw-use-llvm=true",
                "-Dglx=disabled", "-Degl=disabled", "-Dgles1=disabled", "-Dgles2=disabled",
                "-Dopengl=true", "-Dgbm=disabled", "-Dzlib=disabled", "-Dzstd=disabled",
                "-Dexpat=disabled", "-Dbuild-tests=false"]
LLVM_OPTIONS = ["-DCMAKE_BUILD_TYPE=Release", "-DCMAKE_MSVC_RUNTIME_LIBRARY=MultiThreaded",
                "-DLLVM_USE_CRT_RELEASE=MT", "-DLLVM_TARGETS_TO_BUILD=AArch64",
                "-DLLVM_DEFAULT_TARGET_TRIPLE=aarch64-pc-windows-msvc", "-DLLVM_ENABLE_PROJECTS=",
                "-DLLVM_ENABLE_RUNTIMES=", "-DLLVM_INCLUDE_TESTS=OFF", "-DLLVM_INCLUDE_BENCHMARKS=OFF",
                "-DLLVM_ENABLE_ZLIB=OFF", "-DLLVM_ENABLE_ZSTD=OFF", "-DLLVM_ENABLE_LIBXML2=OFF"]


def file_hash(path):
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def tree_manifest(directory):
    files = {}
    if directory.is_symlink():
        raise ValueError(f"cache integrity: symbolic link directory: {directory}")
    for path in sorted(directory.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"cache integrity: symbolic link: {path}")
        if path.is_file():
            files[path.relative_to(directory).as_posix()] = file_hash(path)
    return files


def build_cache_key(configuration):
    return hashlib.sha256(json.dumps(configuration, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def distribution_fingerprint(name):
    distribution = importlib.metadata.distribution(name)
    files = {}
    for member in distribution.files or []:
        # Bytecode is regenerated by Python; installation metadata is not build
        # logic. Hash the underlying binaries/data too, not just pip launchers.
        if member.suffix == ".pyc" or any(part.endswith(".dist-info") for part in member.parts):
            continue
        path = Path(distribution.locate_file(member))
        if path.is_symlink() or not path.resolve().is_relative_to(Path(sys.prefix).resolve()):
            raise ValueError(f"build package must be installed inside the prepared venv: {name}")
        if path.is_file():
            files[member.as_posix()] = file_hash(path)
    if not files:
        raise ValueError(f"missing installed build package contents: {name}")
    return {"version": distribution.version, "files": len(files), "sha256": build_cache_key(files)}


def verify_llvm_cache(entry, configuration):
    receipt = entry / "complete.json"
    if entry.is_symlink() or receipt.is_symlink():
        raise ValueError("LLVM cache integrity: symbolic link entry/receipt")
    if not receipt.exists():
        return False
    record = json.loads(receipt.read_text(encoding="utf-8"))
    if record.get("configuration") != configuration or record.get("key") != build_cache_key(configuration):
        raise ValueError("LLVM cache configuration mismatch")
    actual = tree_manifest(entry / "llvm")
    if not actual or actual != record.get("files"):
        raise ValueError("LLVM cache integrity mismatch; refusing stale/corrupt artifacts")
    return True


def seal_llvm_cache(entry, configuration):
    files = tree_manifest(entry / "llvm")
    if not files:
        raise ValueError("cannot complete an empty LLVM cache")
    record = {"key": build_cache_key(configuration), "configuration": configuration, "files": files}
    partial = entry / "complete.partial"
    partial.write_text(json.dumps(record, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    partial.replace(entry / "complete.json")


def llvm_cache_configuration(env):
    # Only inspect explicitly selected public native SDK directories. Never scan
    # arbitrary process PATHs or unrelated source trees to construct the cache.
    # Windows environment names are case-insensitive. Converting os.environ to
    # a plain dict otherwise loses that property (typically yielding uppercase).
    env = {name.upper(): value for name, value in env.items()}
    roots = [Path(env[name.upper()]).resolve(strict=True) for name in ["VCToolsInstallDir", "WindowsSdkDir"]]
    if env.get("NETFXSDKDIR"):
        roots.append(Path(env["NETFXSDKDIR"]).resolve(strict=True))
    native_inputs = {}
    for variable in ["INCLUDE", "LIB"]:
        directories = []
        for item in env.get(variable, "").split(os.pathsep):
            if not item:
                continue
            directory = Path(item).resolve(strict=True)
            if not any(directory.is_relative_to(root) for root in roots):
                raise ValueError(f"cache fingerprint requires a selected native SDK directory: {directory}")
            files = tree_manifest(directory)
            directories.append({"path": str(directory), "files": len(files), "sha256": build_cache_key(files)})
        native_inputs[variable] = directories
        if not directories:
            raise ValueError(f"native SDK {variable} directories are required for verified reuse")
    tools = {}
    for tool in ["cl.exe", "link.exe", "lib.exe", "rc.exe", "mt.exe", "cmake", "ninja"]:
        path = shutil.which(tool, path=env.get("PATH"))
        if not path:
            raise ValueError(f"missing native build tool: {tool}")
        tools[tool] = {"path": path, "sha256": file_hash(Path(path))}
        if tool == "cl.exe":
            # MSVC loads its frontend/code-generator DLLs beside cl.exe.
            tools[tool]["bin_tree_sha256"] = build_cache_key(tree_manifest(Path(path).parent))
    return {"schema": 1, "source": list(SOURCES["llvm"]), "options": LLVM_OPTIONS,
            "python": {"executable": sys.executable, "version": sys.version, "packages": PACKAGES},
            "toolchain": {name: env.get(name.upper()) for name in ["VCToolsVersion", "WindowsSDKVersion",
                          "VSCMD_ARG_TGT_ARCH", "CL", "_CL_", "LINK", "_LINK_", "CC", "CXX",
                          "CFLAGS", "CXXFLAGS", "LDFLAGS", "CMAKE_TOOLCHAIN_FILE"]},
            "sdk_inputs": native_inputs, "tools": tools}


def llvm_identity(prefix, env):
    executable = prefix / "bin/llvm-config.exe"
    if pe_machine(executable) != 0xaa64:
        raise ValueError("LLVM build is not native ARM64")
    identity = [line.strip() for line in subprocess.check_output(
        [executable, "--version", "--host-target", "--targets-built"], env=env, text=True).splitlines()]
    if identity != ["20.1.8", "aarch64-pc-windows-msvc", "AArch64"]:
        raise ValueError(f"LLVM version/target identity mismatch: {identity}")
    directories = subprocess.check_output(
        [executable, "--prefix", "--libdir", "--includedir", "--cmakedir"], env=env, text=True).splitlines()
    expected = [prefix, prefix / "lib", prefix / "include", prefix / "lib/cmake/llvm"]
    if len(directories) != len(expected) or any(Path(value.strip()).resolve() != path.resolve()
                                               for value, path in zip(directories, expected)):
        raise ValueError(f"LLVM cached installation is not relocated to its verified prefix: {directories}")
    return {"version_target_backends": identity, "installation_directories": directories}


def write_native_machine_file(destination, executable):
    # Preserve the venv executable path: resolving its symlink on Unix changes
    # Python's prefix and loses the prepared dependencies. Meson uses this table
    # for find_program as well as Python-module discovery.
    python = Path(executable).absolute().as_posix()
    quoted = "'" + python.replace("\\", "\\\\").replace("'", "\\'") + "'"
    destination.write_text(f"[binaries]\npython3 = [{quoted}]\npython = [{quoted}]\n", encoding="utf-8")


def source_tree(name, directory):
    url, digest, top = SOURCES[name]
    archive = directory / (name + ".archive")
    if not archive.exists():
        # Interrupted downloads are never promoted into the verified source cache.
        partial = archive.with_suffix(".partial")
        with urllib.request.urlopen(url, timeout=120) as response, partial.open("wb") as output:
            shutil.copyfileobj(response, output)
        partial.replace(archive)
    with archive.open("rb") as verified:
        measured = hashlib.file_digest(verified, "sha256").hexdigest()
    if measured != digest:
        raise ValueError(f"upstream source digest mismatch: {name}")
    destination = directory / top
    if destination.exists():
        raise ValueError(f"refusing stale/modified extracted source; use a fresh --out: {destination}")
    with tarfile.open(archive) as source:
        source.extractall(directory, filter="data")
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", action="store_true")
    parser.add_argument("--out", type=Path, default=ROOT / "target/window-mesa-arm64")
    parser.add_argument("--cache-dir", type=Path, default=ROOT / "target/window-mesa-cache")
    parser.add_argument("--jobs", type=int, default=4)
    args = parser.parse_args()
    output = args.out.resolve()
    cache = args.cache_dir.resolve()
    if not output.is_relative_to(ROOT / "target") or args.jobs < 1:
        parser.error("use a dedicated target directory and a positive job count")
    if not cache.is_relative_to(ROOT / "target") or cache.is_relative_to(output) or output.is_relative_to(cache):
        parser.error("LLVM cache must be a separate directory under this checkout's target")
    plan = {"target": "aarch64-pc-windows-msvc", "sources": SOURCES,
            "python_build_packages": PACKAGES, "mesa_options": MESA_OPTIONS,
            "llvm_options": LLVM_OPTIONS, "llvm_cache_dir": str(cache),
            "child_python": sys.executable, "requires_prepared_venv": True,
            "llvm_targets": ["AArch64"], "crt": "static /MT",
            "executed": False, "runtime_verified": False}
    if args.plan:
        print(json.dumps(plan, indent=2))
        return
    if platform.system() != "Windows" or platform.machine().lower() not in {"arm64", "aarch64"}:
        parser.error("native Windows ARM64 is required; no emulated/x64 driver substitute")
    if os.environ.get("VSCMD_ARG_TGT_ARCH", "").lower() != "arm64":
        parser.error("initialize the VS2022 ARM64 developer environment first")
    if sys.version_info < (3, 12):
        parser.error("Python3.12+ is required for filtered source extraction")
    if sys.prefix == sys.base_prefix:
        parser.error("run this helper with the prepared venv Python; do not modify global packages")
    if os.environ.get("CMAKE_TOOLCHAIN_FILE"):
        parser.error("this native MSVC configuration does not accept an external CMake toolchain file")
    sdk = os.environ.get("WindowsSDKVersion", "").strip("\\").split(".")
    toolset = os.environ.get("VCToolsVersion", "").strip("\\").split(".")
    if len(sdk) < 3 or not sdk[2].isdigit() or int(sdk[2]) < 20348:
        parser.error("Mesa requires Windows SDK20348 or newer")
    if len(toolset) < 2 or tuple(map(int, toolset[:2])) < (14, 39):
        parser.error("Mesa requires VS2022 17.9 / MSVC14.39 or newer")
    for name, version in PACKAGES.items():
        if importlib.metadata.version(name) != version:
            parser.error(f"build package must be pinned: {name}=={version}")
    plan["tool_versions"] = {}
    for tool in ["cmake", "ninja"]:
        executable = shutil.which(tool)
        if not executable or pe_machine(Path(executable)) != 0xaa64:
            parser.error(f"put the pinned native ARM64 {tool} executable on PATH")
        version = subprocess.check_output([executable, "--version"], text=True).splitlines()[0]
        if PACKAGES[tool] not in version:
            parser.error(f"PATH selects a different {tool} version: {version}")
        plan["tool_versions"][tool] = version
    for name in ["MESA_GL_VERSION_OVERRIDE", "MESA_GLSL_VERSION_OVERRIDE"]:
        if os.environ.get(name):
            parser.error(f"remove {name}; actual driver capabilities must remain observable")
    if output.exists() and any(output.iterdir()):
        parser.error("use a fresh --out; verified LLVM reuse is separate from source/driver output")
    output.mkdir(parents=True, exist_ok=True)
    evidence = output / "source-build.json"
    evidence.write_text(json.dumps(plan, indent=2) + "\n")
    env = dict(os.environ, PYTHONNOUSERSITE="1")
    env.pop("PYTHONHOME", None)
    env.pop("PYTHONPATH", None)
    plan["python_identity"] = json.loads(subprocess.check_output(
        [sys.executable, "-c", "import sys,json,importlib.metadata,mako,yaml; "
         "print(json.dumps({'executable':sys.executable,'prefix':sys.prefix,"
         "'Mako':importlib.metadata.version('Mako'),'PyYAML':importlib.metadata.version('PyYAML')}))"],
        env=env, text=True))
    identity = plan["python_identity"]
    if (Path(identity["executable"]).absolute() != Path(sys.executable).absolute()
            or identity["prefix"] != sys.prefix
            or any(identity[name] != PACKAGES[name] for name in ["Mako", "PyYAML"])):
        raise ValueError("prepared child Python/dependency identity mismatch")
    native = output / "native-arm64.ini"
    write_native_machine_file(native, sys.executable)
    plan["meson_native_file"] = native.read_text(encoding="utf-8")
    commands = []

    def run(command):
        command = list(map(str, command))
        commands.append(command)
        plan["commands"] = commands
        evidence.write_text(json.dumps(plan, indent=2) + "\n")
        subprocess.run(command, cwd=output, env=env, check=True)

    sources = output / "sources"
    sources.mkdir(exist_ok=True)
    configuration = llvm_cache_configuration(env)
    configuration["tool_packages"] = {name: distribution_fingerprint(name) for name in ["cmake", "ninja"]}
    entry = cache / build_cache_key(configuration)
    hit = verify_llvm_cache(entry, configuration)
    plan["llvm_cache"] = {"key": entry.name, "hit": hit, "configuration": configuration}
    evidence.write_text(json.dumps(plan, indent=2) + "\n")
    trees = {name: source_tree(name, sources) for name in ["mesa", "winflexbison"]}
    # The source-built parser generators run natively too. Their installed data
    # directory must accompany win_bison; copying just its EXE is insufficient.
    generators = output / "generators"
    run(["cmake", "-S", trees["winflexbison"], "-B", output / "generators-build", "-G", "Ninja",
         "-DCMAKE_BUILD_TYPE=Release", "-DUSE_STATIC_RUNTIME=ON", f"-DCMAKE_INSTALL_PREFIX={generators}"])
    run(["cmake", "--build", output / "generators-build", "--parallel", args.jobs])
    run(["cmake", "--install", output / "generators-build"])
    for name in ["win_flex.exe", "win_bison.exe"]:
        if pe_machine(generators / name) != 0xaa64:
            raise ValueError(f"source-built generator is not ARM64: {name}")
    env["PATH"] = str(generators) + os.pathsep + env["PATH"]
    llvm = entry / "llvm"
    if not hit:
        entry.mkdir(parents=True, exist_ok=True)
        lock = entry / "build.lock"
        lock.mkdir()  # Refuse competing writers or an abandoned in-progress entry.
        try:
            # No completion receipt means no partial installation is reusable.
            if llvm.exists():
                shutil.rmtree(llvm)
            tree = source_tree("llvm", sources)
            compiler = configuration["tools"]["cl.exe"]["path"]
            run(["cmake", "-S", tree / "llvm", "-B", output / "llvm-build", "-G", "Ninja",
                 *LLVM_OPTIONS, f"-DPython3_EXECUTABLE={sys.executable}",
                 f"-DCMAKE_C_COMPILER={compiler}", f"-DCMAKE_CXX_COMPILER={compiler}",
                 f"-DCMAKE_INSTALL_PREFIX={llvm}"])
            run(["cmake", "--build", output / "llvm-build", "--parallel", args.jobs])
            run(["cmake", "--install", output / "llvm-build"])
            plan["llvm_identity"] = llvm_identity(llvm, env)
            seal_llvm_cache(entry, configuration)
        finally:
            lock.rmdir()
    else:
        plan["llvm_identity"] = llvm_identity(llvm, env)
    # Persist cache success before Mesa setup, so a later infrastructure failure
    # can reuse LLVM without accepting an incomplete or stale graphics driver.
    evidence.write_text(json.dumps(plan, indent=2) + "\n")
    env["PATH"] = str(llvm / "bin") + os.pathsep + env["PATH"]
    env["CMAKE_PREFIX_PATH"] = str(llvm)
    install = output / "install"
    run([sys.executable, "-m", "mesonbuild.mesonmain", "setup", output / "mesa-build", trees["mesa"],
         "--native-file", native, f"--prefix={install}", *MESA_OPTIONS])
    plan["meson_build_options"] = json.loads(subprocess.check_output(
        [sys.executable, "-m", "mesonbuild.mesonmain", "introspect", output / "mesa-build", "--buildoptions"],
        env=env, text=True))
    run([sys.executable, "-m", "mesonbuild.mesonmain", "compile", "-C", output / "mesa-build", "-j", args.jobs])
    run([sys.executable, "-m", "mesonbuild.mesonmain", "install", "-C", output / "mesa-build"])
    deploy = output / "driver"
    deploy.mkdir(exist_ok=True)
    libraries = sorted(install.rglob("*.dll"))
    if not {"opengl32.dll", "libgallium_wgl.dll"}.issubset({p.name for p in libraries}):
        raise ValueError("Mesa did not install the actual WGL driver pair")
    plan["driver_files"] = []
    for library in libraries:
        if pe_machine(library) != 0xaa64:
            raise ValueError(f"non-ARM64 driver: {library}")
        shutil.copy2(library, deploy / library.name)
        plan["driver_files"].append({"name": library.name, "machine": "ARM64",
                                     "sha256": hashlib.sha256(library.read_bytes()).hexdigest()})
    plan["executed"] = True
    plan["os"] = platform.platform()
    plan["msvc_toolset"] = os.environ.get("VCToolsVersion")
    plan["windows_sdk"] = os.environ.get("WindowsSDKVersion")
    evidence.write_text(json.dumps(plan, indent=2) + "\n")
    print(f"Built native source driver at {deploy}; runtime remains REQUIRED via window_render_wgl_ci.py")


if __name__ == "__main__":
    main()
