#!/usr/bin/env python3
"""Generate the fuzz target listings from fuzz/targets.json, or check that they are current.

    python3 tools/fuzz/sync_targets.py           # rewrite fuzz/Cargo.toml [[bin]] entries and fuzz/harness/tests/regressions.rs
    python3 tools/fuzz/sync_targets.py --check   # exit 1 when either differs, or a fuzz_targets/<name>.rs file is missing
"""
import argparse
import json
import sys


from toolkit.repo import ROOT

FUZZ = ROOT / "fuzz"
CARGO = FUZZ / "Cargo.toml"
REGRESSIONS = FUZZ / "harness" / "tests" / "regressions.rs"

CARGO_MARK = "# Generated by tools/fuzz/sync_targets.py from fuzz/targets.json; do not edit below this line.\n"
RS_BEGIN = "// BEGIN generated by tools/fuzz/sync_targets.py from fuzz/targets.json\n"
RS_END = "// END generated\n"


def target_names() -> list[str]:
    return list(json.loads((FUZZ / "targets.json").read_text()))


def cargo_text(current: str, names: list[str]) -> str:
    head, sep, _ = current.partition(CARGO_MARK)
    head = head.rstrip("\n") + "\n\n" if sep else current.rstrip("\n") + "\n\n"
    bins = "\n".join(
        f'[[bin]]\nname = "{n}"\npath = "fuzz_targets/{n}.rs"\ntest = false\ndoc = false\nbench = false\n' for n in names
    )
    return head + CARGO_MARK + "\n" + bins


def regressions_text(current: str, names: list[str]) -> str:
    begin, end = current.index(RS_BEGIN), current.index(RS_END)
    tests = "\n".join(
        f'#[test]\nfn {n}() {{\n    replay("{n}", jai_fuzz_harness::{n});\n}}\n' for n in names
    )
    return current[:begin] + RS_BEGIN + "\n" + tests + "\n" + current[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    names = target_names()
    failures = [f"fuzz/fuzz_targets/{n}.rs is missing" for n in names if not (FUZZ / "fuzz_targets" / f"{n}.rs").is_file()]
    for path, build in ((CARGO, cargo_text), (REGRESSIONS, regressions_text)):
        current = path.read_text()
        wanted = build(current, names)
        if wanted == current:
            continue
        if check:
            failures.append(f"{path.relative_to(ROOT)} is out of date; run python3 tools/fuzz/sync_targets.py")
        else:
            path.write_text(wanted)
    for failure in failures:
        print(failure, file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
