#!/usr/bin/env python3
"""Writes stdlib/Extensions/Regex/tests/data/differential_cases.jai: random patterns and texts,
with what Rust's regex crate matches for each (via tools/regex_oracle). The Jai test checks that
Extensions/Regex finds the same matches and capture spans. See docs/extensions/regex.md.

    cargo build --release --manifest-path tools/regex_oracle/Cargo.toml
    python3 tools/gen_regex_corpus.py --oracle tools/regex_oracle/target/release/regex-oracle
"""

import argparse
import pathlib
import random
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "stdlib/Extensions/Regex/tests/data/differential_cases.jai"

ATOMS = [
    "a", "b", "c", "ab", "\\d", "\\w", "\\s", "\\W", ".", "[a-c]", "[^ab]", "\\b", "\\B", "^", "$",
    "(?m:^)", "(?m:$)", "é", "α", "\\p{Greek}", "[[:alpha:]]", "\\x41", "(?i:A)", "(?i)b",
    "[a-z&&[^c]]", "\\<", "\\>", "\\b{start}", "\\b{end}", "\\A", "\\z", "(?s:.)", "(?-u:\\w)",
    "(?-u:\\b)", "x", "\\n", "[\\d--5]", "[a~~b]", "(?U)a+", "\\pL",
]
WIDE_ATOMS = [
    "(?i)σ", "(?i)k", "(?i)ſ", "(?i)[a-zσ]", "(?i)[^k]", "(?i)\\w", "(?i)\\p{Lu}", "(?x) a b # c\n",
    "(?x)[a b]", "(?mR)^", "(?mR)$", "(?R).", "\\p{Lu}", "\\P{Ll}", "[[:^digit:]]", "\\u{3b1}",
    "[\\p{Greek}&&\\p{Ll}]", "\\p{scx=Greek}", "\\p{gc=Nd}", "\\pN", "(?i)ǅ", "(?i)[ǆ-ǈ]",
    "[\\x00-\\x7f]", "(?-u:[\\x00-\\x7f])", "[^\\s\\d]", "(?i:Ω)", "(?is).", "(?U)a*?", "(?i)ß",
    "\\b{start-half}", "\\b{end-half}", "(?m)$", "(?m)^", "[\\[\\]]", "\\.", "a{0}", "(a|)+",
    "(|a)*", "(?:a?)*", "()",
]
# Patterns that must not compile.
BAD = ["(?<", "a{2,1}", "\\1", "[z-a]", "(?P<n>a)(?P<n>b)", "\\p{Bogus}", "(?:", "a**", "[a-\\d]",
       "\\k", "a{,2}", "(?=a)", "x{10001}"]
TEXT = list("aabbcc  xX\n-1259_") + ["é", "α", "β", "Ω", "\r"]
WIDE_TEXT = ["K", "k", "\u212a", "σ", "ς", "Σ", "ſ", "s", "S", "ǅ", "ǆ", "Ǆ", "ß", "ẞ", "ω", "٣",
             "\t", "#", "[", "]", "."]


def pattern(rng, atoms, depth=0):
    r = rng.random()
    if depth > 3 or r < 0.3:
        return rng.choice(atoms)
    sub = lambda: pattern(rng, atoms, depth + 1)
    if r < 0.5:
        return sub() + sub()
    if r < 0.6:
        return sub() + "|" + sub()
    if r < 0.75:
        return "(" + sub() + ")"
    if r < 0.8:
        return "(?<n%d>" % rng.randint(0, 999) + sub() + ")"
    if r < 0.85:
        return "(?:" + sub() + ")" + rng.choice(["*", "+", "?", "*?", "+?", "??"])
    return "(" + sub() + ")" + rng.choice(["*", "+", "?", "{2}", "{1,3}", "{0,2}?", "{2,}", "*?", "+?"])


def cases():
    rng = random.Random(20261011)
    out = []
    for _ in range(150):
        out.append((pattern(rng, ATOMS), "".join(rng.choice(TEXT) for _ in range(rng.randint(0, 14)))))
    atoms, chars = ATOMS + WIDE_ATOMS * 2, TEXT + WIDE_TEXT
    for i in range(150):
        size = rng.randint(100, 300) if i % 10 == 0 else rng.randint(0, 14)
        out.append((pattern(rng, atoms), "".join(rng.choice(chars) for _ in range(size))))
    for bad in BAD:
        out.append((bad, "a"))
    return out


def jai_string(s):
    escapes = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    return '"' + "".join(escapes.get(c, c) for c in s) + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--oracle", required=True, help="the built tools/regex_oracle binary")
    args = parser.parse_args()
    all_cases = cases()
    lines = "".join(p.encode().hex() + "\t" + t.encode().hex() + "\n" for p, t in all_cases)
    result = subprocess.run([args.oracle], input=lines, capture_output=True, text=True, check=True)
    expected = result.stdout.splitlines()
    assert len(expected) == len(all_cases)
    body = ["// Generated by tools/gen_regex_corpus.py from Rust's regex 1.13.1. Do not edit.",
            "// Each case: pattern, text, and every match's capture spans (see differential.jai).", "",
            "CASES :: Case.["]
    for (p, t), e in zip(all_cases, expected):
        body.append("    .{ %s, %s, %s }," % (jai_string(p), jai_string(t), jai_string(e)))
    body.append("];")
    OUTPUT.write_text("\n".join(body) + "\n")
    print(f"wrote {len(all_cases)} cases to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
