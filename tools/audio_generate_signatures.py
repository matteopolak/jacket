#!/usr/bin/env python3
"""Generate compile/link probes from reviewed procedure declarations.

These preserve parameter labels/defaults and procedure flags where accepted by
the type grammar. An inferred bool return is spelled explicitly in the probe.
They are not a behavioral oracle.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    spec = (ROOT / "docs/specs/stdlib/modules/sound-player.md").read_text()
    inventory = spec.split("## Public aggregate shapes")[0]
    lines = ['// Generated by tools/audio_generate_signatures.py; compile/link evidence only.',
             '#import "Basic";', '#import "Math";', '#import "Thread";',
             '#import "Sound_Player";', '']
    checks = []
    for index, line in enumerate(inventory.splitlines()):
        match = re.match(r"- (?:\[(.*?)\] )?`(\w+)\s*::\s*(\(.*?)`", line)
        if not match:
            continue
        condition, name, signature = match.groups()
        if "$T" in signature:
            continue
        signature = signature.replace("success := true", "success: bool = true")
        declaration = f"Expected_{index} :: #type {signature};\nprobe_{index}: Expected_{index} = {name};"
        check = f"    assert(probe_{index} != null);"
        if condition:
            declaration = f"#if {condition} {{\n{declaration}\n}}"
            check = f"    #if {condition} assert(probe_{index} != null);"
        lines += [declaration, ""]
        checks.append(check)
    lines += ["main :: () {", *checks, '    print("ok\\n");', "}", "",
              "#scope_file", "#if OS == .WINDOWS {", '    W :: #import "Windows";',
              '    Wave :: #import "Wav_File";', "    GUID :: W.GUID;",
              "    Waveformatex :: Wave.Waveformatex;", "}"]
    (ROOT / "tests/audio/signatures.jai").write_text("\n".join(lines) + "\n")
    print(f"Generated {len(checks)} signature/link probes; omitted generic ring helper.")


if __name__ == "__main__":
    main()
