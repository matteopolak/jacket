#!/usr/bin/env python3
"""Emit portable scalar-lane kernels grouped independently by operation family.

Public names/headers/flags come from reviewed SIMD declarations. Behavioral
choices not established there remain explicit in docs/portable-simd.md.
"""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
parts = ["""// Generated by tools/generate_simd_lanes.py. Real scalar fallback kernels.
set :: ($N: s64, factor: $T) -> SIMD_Array(N, T) #no_abc #no_aoc {
    result: SIMD_Array(N, T);
    for 0..N - 1 result.data[it] = factor;
    return result;
}

store :: (base: *void, a: $T/SIMD_Array) #no_abc #no_aoc {
    B.assert(base != null || a.count == 0, "SIMD store requires writable storage");
    memcpy(base, a.data.data, size_of(T));
}
"""]
for operation in ["+", "-", "*", "/"]:
    for scalar in [False, True]:
        other = "factor: a.type" if scalar else "b: T"
        expression = "factor" if scalar else "b.data[it]"
        symmetric = " #symmetric" if scalar else ""
        parts.append(f"""
operator {operation} :: (a: $T/SIMD_Array, {other}) -> T{symmetric} #no_abc #no_aoc {{
    result: T;
    for 0..a.count - 1 result.data[it] = a.data[it] {operation} {expression};
    return result;
}}
""")
for operation in ["==", "!=", ">", ">=", "<", "<="]:
    for scalar in [False, True]:
        other = "factor: a.type" if scalar else "b: T"
        expression = "factor" if scalar else "b.data[it]"
        parts.append(f"""
operator {operation} :: (a: $T/SIMD_Array, {other}) -> T #no_abc #no_aoc {{
    result: T;
    for 0..a.count - 1 write_mask(*result.data[it], size_of(a.type), a.data[it] {operation} {expression});
    return result;
}}
""")
for operation in ["min", "max"]:
    for scalar in [False, True]:
        other = "factor: a.type" if scalar else "b: T"
        expression = "factor" if scalar else "b.data[it]"
        parts.append(f"""
{operation} :: (a: $T/SIMD_Array, {other}) -> T #no_abc #no_aoc {{
    result: T;
    for 0..a.count - 1 result.data[it] = B.{operation}(a.data[it], {expression});
    return result;
}}
""")
parts.append("""
horizontal_sum :: (a: $T/SIMD_Array) -> a.type {
    return sum_lanes(a);
}

get_mask :: (a: $T/SIMD_Array) -> s64 {
    #assert a.count <= 64;
    #assert size_of(a.type) == 1 || size_of(a.type) == 2 || size_of(a.type) == 4 || size_of(a.type) == 8;
    probe: u16 = 1;
    byte_index: s64;
    if (cast(*u8) *probe)[0] == 1 byte_index = size_of(a.type) - 1;
    bits: u64;
    one: u64 = 1;
    for 0..a.count - 1 {
        p := cast(*u8) *a.data[it];
        if (p[byte_index] & 0x80) != 0 bits |= one << it;
    }
    result: s64;
    memcpy(*result, *bits, 8);
    return result;
}

#scope_file
B :: #import "Basic";

write_mask :: (target: *void, bytes: s64, condition: bool) {
    value: u8;
    if condition value = 255;
    memset(target, value, bytes);
}

sum_lanes :: (a: $T/SIMD_Array) -> a.type #no_aoc {
    result: a.type;
    for a.data result += it;
    return result;
}
""")
path = ROOT / "stdlib/internal/simd/lanes.jai"
path.write_text("\n".join(parts))
subprocess.run([str(ROOT / "target/jaifmt"), "--config", str(ROOT / "jaifmt.toml"), str(path)], check=True)
