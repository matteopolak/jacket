#!/usr/bin/env python3
"""Turns the vendored JSONTestSuite cases into stdlib/Extensions/Json/tests/fixtures/suite_cases.jai,
so the Json tests need no file system (they also run under wasm).

    python3 tools/corpus/gen_json_corpus.py
"""

import sys as _sys
from pathlib import Path as _Path

_TOOLS = _Path(__file__).resolve().parents[1]
_sys.path[:0] = [str(_TOOLS / "generators")]  # modules from other tools/ folders

import argparse
import os

from jai_codegen import write_or_check

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "stdlib", "Extensions", "Json", "tests", "fixtures")
SOURCE = os.path.join(ROOT, "JSONTestSuite", "test_parsing")
OUTPUT = os.path.join(ROOT, "suite_cases.jai")


def literal(data: bytes) -> str:
    out = ['"']

    for b in data:
        c = chr(b)

        if c == '"':
            out.append('\\"')
        elif c == "\\":
            out.append("\\\\")
        elif 0x20 <= b < 0x7F and c != "%":
            out.append(c)
        else:
            out.append("\\x%02x" % b)

    out.append('"')

    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if the checked-in file differs from the output instead of writing it")
    args = parser.parse_args()
    names = sorted(n for n in os.listdir(SOURCE) if n.endswith(".json"))
    lines = [
        "// Generated by tools/corpus/gen_json_corpus.py from data/JSONTestSuite/test_parsing. Do not edit.",
        "",
        "Suite_Case :: struct {",
        "    name: string;",
        "    text: string;",
        "}",
        "",
        "SUITE_CASES :: Suite_Case.[",
    ]

    for name in names:
        with open(os.path.join(SOURCE, name), "rb") as f:
            data = f.read()

        lines.append("    .{ %s, %s }," % (literal(name[:-5].encode()), literal(data)))

    lines.append("];")

    write_or_check(OUTPUT, "\n".join(lines) + "\n", args.check)

    print(("verified" if args.check else "wrote") + " %d cases" % len(names))


if __name__ == "__main__":
    main()
