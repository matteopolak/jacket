#!/usr/bin/env python3
"""Regenerates stdlib/Extensions/Postgres/saslprep_data.jai: the compatibility mappings of
Unicode NFKC for single code points, which SASLprep (RFC 4013) applies to passwords.

    python3 tools/pg_conformance/gen_saslprep.py

The mapping comes from the Unicode data in Python's `unicodedata`, so the output follows the
Python that runs this. Sequences of a base character and combining marks are not recomposed
(docs/extensions/postgres.md).
"""

from __future__ import annotations

import unicodedata


from toolkit.repo import ROOT

OUTPUT = ROOT / "stdlib" / "Extensions" / "Postgres" / "saslprep_data.jai"
WRAP = 12


def rows(name: str, values: list[int]) -> list[str]:
    lines = [f"{name} :: u32.["]
    for start in range(0, len(values), WRAP):
        lines.append("    " + ", ".join(f"0x{v:X}" for v in values[start:start + WRAP]) + ",")
    lines.append("];")
    return lines


def main() -> None:
    keys: list[int] = []
    starts: list[int] = []
    chars: list[int] = []

    for code in range(0x110000):
        if 0xD800 <= code < 0xE000:
            continue
        text = chr(code)
        mapped = unicodedata.normalize("NFKC", text)
        if mapped == text:
            continue
        keys.append(code)
        starts.append(len(chars))
        chars.extend(ord(c) for c in mapped)
    starts.append(len(chars))

    out = [
        "// Generated by tools/pg_conformance/gen_saslprep.py from Unicode " + unicodedata.unidata_version + "; do not edit.",
        "// The NFKC form of every code point it changes: the code points, where each result starts in",
        "// SASLPREP_CHARS (one entry more than there are code points), and the results.",
        "",
        *rows("SASLPREP_CODES", keys),
        "",
        *rows("SASLPREP_STARTS", starts),
        "",
        *rows("SASLPREP_CHARS", chars),
        "",
    ]
    OUTPUT.write_text("\n".join(out))
    print(f"{OUTPUT}: {len(keys)} mappings")


if __name__ == "__main__":
    main()
