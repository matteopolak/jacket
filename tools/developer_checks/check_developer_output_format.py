#!/usr/bin/env python3
"""The text printed for bitfield records and C++ vtables, against the layout of the official generator's output.

`bindings-output-format.hpp` is the probe header the layout was taken from (a bitfield record, a record with
several units, and a base interface with two derived ones), and `bindings-output-format-expected.txt` is the text
the generator must print for it. The expected text follows the official generator's printed output for the same
header (`set_`/`get_` procedures after the record, `/* ... */` member lists, `Name_VTable` records with
`using vtable:` and `#cpp_method` slots, `#as using,except(vtable)` bases with `#overlay`, `Record_method` wrappers
and `vtable(obj)`) except where this generator deliberately differs:

- `Flags { int a : 3; unsigned b : 1; bool c : 1; }` is one `u32` unit holding all three members, as the C compiler
  lays it out. The official output splits `c` into a separate `bool #align 1` field at offset 0 and forces the record
  to 4 bytes with a `[0] u32` member.
- `get_a` sign-extends: a signed member narrower than its type reads back negative values. The official getter
  returns the masked bits.
- The member list has no space after `/*` and no `;` after the last member's comment.
- A virtual method no library defines gets no `virtual_<method>` foreign declaration (and so no explanatory comment);
  the official output declares one against `__UnknownLib` for every method.
- Everything that is not about bitfields or vtables keeps this generator's own style: the `// Generated by` header,
  one-space indentation, the record's `#align` on its first member, `float32`, records in dependency order (`ISession` before the
  interface it derives from, because the header declares it first), no blank lines between declarations, and the
  `#assert` lines under `#scope_file` in place of the official `#run` checks.
"""
import difflib
import os
import platform

from developer_checks.dev_common import ENV, JAIC, labeled_runner
from developer_checks.driven_sources import driven
from repo_output import output_dir
from developer_checks import build_developer_bindings


def main():
    if platform.system() == "Windows":
        # MSVC orders the slots of overloads differently, so the expected text is for the Itanium ABI.
        print("bitfield and vtable output format: Itanium ABI hosts only")
        return

    prefix = build_developer_bindings.llvm_prefix()
    work = output_dir("output-format")
    work.mkdir(parents=True, exist_ok=True)
    env = dict(ENV, JAIC_NATIVE_LIBS=os.pathsep.join(filter(None, [str(prefix / "lib"), ENV.get("JAIC_NATIVE_LIBS")])))
    run = labeled_runner("Output format", env=env, timeout=180)
    generated = work / "generated.jai"

    run([JAIC, driven("bindings-output-format.jai"), "-interp", "--", generated], "ok\n")

    expected = driven("bindings-output-format-expected.txt").read_text()
    actual = generated.read_text()

    if actual != expected:
        diff = "".join(difflib.unified_diff(expected.splitlines(True), actual.splitlines(True), "expected", "generated"))
        raise RuntimeError("generated bindings differ from bindings-output-format-expected.txt:\n" + diff)

    # The text must also be Jai that compiles, and the accessors must work on the records it describes.
    consumer = work / "consumer.jai"
    consumer.write_text(
        '#import "Basic";\n#load "generated.jai";\n'
        "main :: () {\n"
        "    flags: Flags;\n    set_a(*flags, -3);\n    set_b(*flags, true);\n    set_c(*flags, true);\n"
        "    assert(get_a(flags) == -3 && get_b(flags) && get_c(flags));\n"
        "    set_a(*flags, 1);\n    assert(get_a(flags) == 1 && get_b(flags) && get_c(flags));\n"
        "    operand: VMExecOperand;\n    set_type(*operand, 0xab);\n    set_size(*operand, 0x123456);\n"
        "    assert(get_type(operand) == 0xab && get_size(operand) == 0x123456);\n"
        "    session: ISession;\n    table: ISession_VTable;\n    session.vtable = *table;\n"
        "    assert(vtable(*session) == *table && size_of(Flags) == 4 && size_of(ISession) == 8);\n"
        "    unknown: *IUnknownish = *session;\n    assert(cast(*void) unknown.vtable == cast(*void) *table);\n"
        '    print("ok\\n");\n}\n'
    )
    run([JAIC, consumer, "-interp"], "ok\n")
    print("bitfield and vtable output matches the expected layout and the generated bindings run")


if __name__ == "__main__":
    main()
