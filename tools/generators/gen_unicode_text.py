#!/usr/bin/env python3
"""Generate compact normalization and segmentation tables from the shared pinned UCD."""
from generators.gen_regex_unicode import open_source, data_lines, parse_span, MAX_CP
from toolkit.repo import ROOT
from generators.jai_codegen import emit_generated, generator_parser

OUTPUTS = ["stdlib/Extensions/Unicode_Text/properties_data.jai", "stdlib/Extensions/Unicode_Text/normalization_data.jai"]
DOWNLOADS = True
FORMATTED = True


def array(name, values, kind):
    rows = [", ".join(str(x) for x in values[i:i + 16]) for i in range(0, len(values), 16)]
    return f"{name}: [] {kind} = {kind}.[\n" + ",\n".join(rows) + "];\n"


def staged(name, values, kind):
    blocks, index, payload = {}, [], []
    for start in range(0, len(values), 256):
        block = tuple(values[start:start + 256])
        if block not in blocks:
            blocks[block] = len(payload) // 256
            payload.extend(block)
        index.append(blocks[block])
    assert len(blocks) < 65536
    assert all(payload[index[c >> 8] * 256 + (c & 255)] == v for c, v in enumerate(values))
    return array(name + "_index", index, "u16") + array(name + "_values", payload, kind)


def generate(source):
    props = [0] * (MAX_CP + 1)
    enums = ""
    for name, filename, shift, default in [
        ("G", "auxiliary/GraphemeBreakProperty.txt", 8, "Other"),
        ("W", "auxiliary/WordBreakProperty.txt", 12, "Other"),
        ("S", "auxiliary/SentenceBreakProperty.txt", 17, "Other"),
    ]:
        rows = list(data_lines(source.read(filename)))
        labels = [default] + sorted({r[1] for r in rows} - {default})
        assert len(labels) <= (32 if name == "W" else 16)
        enums += f"{name} :: enum u8 {{ " + "; ".join(labels) + "; }\n"
        for span, label, *_ in rows:
            lo, hi = parse_span(span)
            for cp in range(lo, hi + 1):
                props[cp] |= labels.index(label) << shift
    for row in data_lines(source.read("DerivedCoreProperties.txt")):
        if row[1] == "InCB":
            lo, hi = parse_span(row[0])
            for cp in range(lo, hi + 1):
                props[cp] |= {"Consonant": 1, "Extend": 2, "Linker": 3}[row[2]] << 21
    for row in data_lines(source.read("emoji/emoji-data.txt")):
        if row[1] == "Extended_Pictographic":
            lo, hi = parse_span(row[0])
            for cp in range(lo, hi + 1):
                props[cp] |= 1 << 23
    excluded = set()
    for row in data_lines(source.read("DerivedNormalizationProps.txt")):
        lo, hi = parse_span(row[0])
        if row[1] == "Full_Composition_Exclusion":
            excluded.update(range(lo, hi + 1))
        if row[1] in ("NFC_QC", "NFD_QC", "NFKC_QC", "NFKD_QC"):
            shift = 24 + 2 * ("NFC_QC", "NFD_QC", "NFKC_QC", "NFKD_QC").index(row[1])
            for cp in range(lo, hi + 1):
                props[cp] |= {"N": 1, "M": 2}[row[2]] << shift
    raw, pairs = {}, {}
    for row in data_lines(source.read("UnicodeData.txt")):
        cp = int(row[0], 16)
        props[cp] |= int(row[3])
        parts = row[5].split()
        if not parts:
            continue
        compat = parts[0].startswith("<")
        sequence = [int(x, 16) for x in parts[compat:]]
        raw[cp] = compat, sequence
        if not compat and len(sequence) == 2 and cp not in excluded:
            pairs[(sequence[0] << 21) | sequence[1]] = cp

    def expand(cp, compatibility):
        if 0xAC00 <= cp <= 0xD7A3:
            n = cp - 0xAC00
            return [0x1100 + n // 588, 0x1161 + n % 588 // 28] + ([0x11A7 + n % 28] if n % 28 else [])
        if cp not in raw or (raw[cp][0] and not compatibility):
            return [cp]
        return [c for child in raw[cp][1] for c in expand(child, compatibility)]

    pool, offsets = [], {}
    mappings = []
    for compatibility in (False, True):
        mapping = [0] * (MAX_CP + 1)
        for cp in raw:
            sequence = tuple(expand(cp, compatibility))
            if sequence == (cp,):
                continue
            if sequence not in offsets:
                offsets[sequence] = len(pool) | (len(sequence) << 24)
                pool.extend(sequence)
            mapping[cp] = offsets[sequence]
        mappings.append(mapping)
    header = "// Generated by tools/generators/gen_unicode_text.py; UCD 17.0.0. Do not edit.\n// Unicode data: see LICENSE.txt in this directory.\n#scope_module\n"
    properties = header + enums + staged("properties", props, "u32")
    normalization = header + staged("canonical", mappings[0], "u32") + staged("compatibility", mappings[1], "u32")
    normalization += array("decompositions", pool, "u32")
    normalization += array("composition_keys", sorted(pairs), "u64")
    normalization += array("composition_values", [pairs[k] for k in sorted(pairs)], "u32")
    return properties, normalization


def main():
    parser = generator_parser(__doc__)
    parser.add_argument("--ucd")
    parser.add_argument("--zip")
    args = parser.parse_args()
    for filename, text in zip(OUTPUTS, generate(open_source(args))):
        emit_generated(ROOT / filename, text, args.formatter, args.check)


if __name__ == "__main__":
    main()
