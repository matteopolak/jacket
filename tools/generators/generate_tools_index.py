#!/usr/bin/env python3
"""Write tools/README.md: every entry-point script under tools/ with its purpose and who runs it.

    python3 tools/generators/generate_tools_index.py [--check]

An entry point is a Python file with a `__main__` guard that is not a test, not part of `toolkit/` and not a
test fixture. Its purpose is the first line of its module docstring. Its callers are the places that name it:
`CI` (a workflow or composite action), `just` (the Justfile) and `tools` (another script, shell file or data
file under tools/). A script nothing names is listed with `-`; it is run by hand. Docs do not count as
callers, so a docs-only change cannot make the index stale.

There is deliberately no single front-door script: job selection (docs/tools/ci-job-selection.md) reads the
script paths out of the workflows' `run:` lines, and one front door would hide them.
"""

import argparse
import ast
from pathlib import Path
import re
import subprocess
import sys
from toolkit.repo import ROOT

OUTPUTS = ["tools/README.md"]

INDEX = "tools/README.md"
SKIPPED_PARTS = {"__pycache__", "node_modules", "target", "fixtures"}
MAIN_GUARD = re.compile(r"""^if\s+__name__\s*==\s*["']__main__["']\s*:""", re.MULTILINE)
TEXT_SUFFIXES = {".py", ".sh", ".yml", ".yaml", ".json", ".mjs", ".ps1", ".toml", ".nix"}

HEADER = """# Tools

Generated by `tools/generators/generate_tools_index.py`; do not edit it by hand (`check_generated.py` fails when it is stale).

Every Python entry point under `tools/`, by folder. Run one with `PYTHONPATH=tools python3 tools/<folder>/<script>.py`.
Folder layout, conventions and the shared `toolkit/` are in [docs/tools/tools-layout.md](../docs/tools/tools-layout.md).

**Called by** says where a script is named: `CI` (a workflow or composite action), `just` (the Justfile), `tools`
(another script, shell file or data file under `tools/`). A `-` means nothing names it: it is run by hand
(a bench, a probe, a corpus fetcher or a generator). Docs do not count.

There is no single front-door script on purpose: CI job selection reads script paths out of the workflows, and one
front door would hide them.
"""


def tracked_files(root):
    """Repo-relative paths of the tracked and not-ignored files."""
    out = subprocess.check_output(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"], cwd=root
    )
    return sorted(Path(name) for name in out.decode().split("\0") if name)


def entry_points(root, files):
    """The entry-point scripts among `files`."""
    found = []
    for path in files:
        parts = path.parts
        if path.suffix != ".py" or parts[0] != "tools" or len(parts) < 2 or not (root / path).is_file():
            continue
        if path.name.startswith("test_") or (len(parts) > 2 and parts[1] == "toolkit") or SKIPPED_PARTS & set(parts):
            continue
        if MAIN_GUARD.search((root / path).read_text(encoding="utf-8")):
            found.append(path)
    return found


def purpose(root, path):
    """The first line of the module docstring, or a placeholder."""
    doc = ast.get_docstring(ast.parse((root / path).read_text(encoding="utf-8"))) or ""
    line = doc.strip().split("\n")[0].strip() if doc.strip() else ""
    return (line or "(no docstring)").replace("|", "\\|")


WORD = re.compile(r"[\w/.-]+")


def words(text):
    """The names a file can use to refer to a script: every path-like word (trailing punctuation cut), and for
    a dotted word every leading run of its parts (`tools.a.run.main` also gives `tools.a.run`)."""
    found = set()
    for word in WORD.findall(text):
        word = word.rstrip(".-/")
        found.add(word)
        if "/" not in word and "." in word:
            parts = word.split(".")
            found.update(".".join(parts[:n]) for n in range(1, len(parts)))
    return found


def category(file):
    """`CI`, `just` or `tools` for a file that can call a script, else None."""
    name = file.as_posix()
    if name.startswith(".github/"):
        return "CI"
    if name == "Justfile":
        return "just"
    if name.startswith("tools/") and file.suffix in TEXT_SUFFIXES and not file.name.startswith("test_"):
        return "tools"
    return None


def callers(root, files, scripts):
    """Each script's sorted caller categories."""
    named = {}
    for file in files:
        kind = category(file)
        if kind is None or file.as_posix() == INDEX or not (root / file).is_file():
            continue
        named[file] = (kind, words((root / file).read_text(encoding="utf-8", errors="replace")))
    result = {}
    for script in scripts:
        path = script.as_posix()
        dotted = path[:-3].replace("/", ".")
        found = set()
        for file, (kind, names) in named.items():
            if file == script:
                continue
            # Another script of the same folder may name it by file name alone; elsewhere the path is needed.
            if path in names or dotted in names or (file.parent == script.parent and script.name in names):
                found.add(kind)
        if script.parent.name == "generators" or "OUTPUTS" in (root / script).read_text(encoding="utf-8"):
            if script.name != "check_generated.py":
                found.add("tools")  # tools/generators/check_generated.py discovers and runs it
        result[script] = sorted(found, key=("CI", "just", "tools").index)
    return result


def render(root):
    files = tracked_files(root)
    scripts = entry_points(root, files)
    who = callers(root, files, scripts)
    lines = [HEADER]
    def folder_of(script):
        return script.parts[1] if len(script.parts) > 2 else ""

    for folder in sorted({folder_of(script) for script in scripts}):
        mine = [script for script in scripts if folder_of(script) == folder]
        lines.append(f"## `{folder}/`\n" if folder else "## Top level\n")
        lines.append("| Script | What it does | Called by |")
        lines.append("| --- | --- | --- |")
        for script in mine:
            name = "/".join(script.parts[2:] if folder else script.parts[1:])
            called = ", ".join(who[script]) or "-"
            lines.append(f"| `{name}` | {purpose(root, script)} | {called} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if tools/README.md differs instead of writing it")
    args = parser.parse_args()
    text = render(ROOT)
    target = ROOT / INDEX
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            print(f"stale generated file: {INDEX}; run python3 tools/generators/generate_tools_index.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
