#!/usr/bin/env python3
"""Record the release each documented standard-library item first appeared in, for `jacket doc`.

    python3 tools/generators/generate_doc_since.py [--check] [--full] [--jaic <path>]

`crates/jacket/src/doc/since.tsv` lists, for every release tag (`vX.Y.Z`) it covers, the items that tag's
`stdlib/` has and no earlier tag had, as the compiler's documentation model sees them (`jaic -doc_model`).
The items of the oldest covered tag are listed under `-`: they are older than the data. Run without
arguments after a release is tagged: it reads the file, adds the tags it does not cover yet (each one
extracted with `git archive`, so the checkout is not touched) and writes it back. `--full` starts again from
every tag, which can move an item if the compiler's reading of an old release has changed.

`--check` does not read any tag's sources: it checks that the file is well formed and covers tags that exist
here, in order. It notes (and does not fail on) tags that are newer than the file, so tagging a release never
turns the checks red; `jacket doc` gives items it has no row for the version it is built as.

Format: a `# covers: v0.18.0 v0.19.0 ...` line, then `Module<TAB>version<TAB>name name ...` rows.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
from toolkit.repo import ROOT, cargo_binary

OUTPUTS = ["crates/jacket/src/doc/since.tsv"]

TARGET = ROOT / OUTPUTS[0]
TAG = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")
SKIPPED = {"internal", "prelude", "tests"}
BASELINE = "-"


def tags():
    """Every `vX.Y.Z` tag of the checkout, oldest first."""
    out = subprocess.run(["git", "tag", "-l", "v*"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    found = [t for t in out.split() if TAG.match(t)]
    return sorted(found, key=lambda t: tuple(int(n) for n in TAG.match(t).groups()))


def read(path):
    """(covered tags, {(module, name): version}) of a data file, or ([], {}) when there is none."""
    if not path.is_file():
        return [], {}
    covered, seen = [], {}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("# covers:"):
            covered = line.split(":", 1)[1].split()
        elif line and not line.startswith("#"):
            parts = line.split("\t")
            if len(parts) != 3:
                raise ValueError(f"{path}:{number}: expected module, version and names separated by tabs")
            for name in parts[2].split(" "):
                seen[(parts[0], name)] = parts[1]
    return covered, seen


def render(covered, seen):
    rows = {}
    for (module, name), version in seen.items():
        rows.setdefault((module, version), []).append(name)
    order = {BASELINE: -1, **{t[1:]: i for i, t in enumerate(covered)}}
    lines = [
        "# The release each documented item first appeared in; generated by tools/generators/generate_doc_since.py.",
        "# covers: " + " ".join(covered),
    ]
    for (module, version), names in sorted(rows.items(), key=lambda kv: (kv[0][0], order.get(kv[0][1], 1 << 30))):
        lines.append(f"{module}\t{version}\t{' '.join(sorted(names))}")
    return "\n".join(lines) + "\n"


def modules(stdlib):
    """The ids of the libraries below `stdlib`, as `jacket doc` finds them."""
    found = []

    def walk(directory, prefix):
        for entry in sorted(p for p in directory.iterdir() if p.is_dir()):
            if entry.name.startswith(".") or entry.name in SKIPPED:
                continue
            ident = f"{prefix}/{entry.name}" if prefix else entry.name
            if (entry / "module.jai").is_file():
                found.append(ident)
            walk(entry, ident)

    walk(stdlib, "")
    return found


def items_at(tag, jaic):
    """The `Module/name` pairs documented in the standard library at `tag`."""
    with tempfile.TemporaryDirectory(prefix="doc-since-") as scratch:
        archive = subprocess.run(["git", "archive", tag, "stdlib"], cwd=ROOT, capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "-C", scratch], input=archive, check=True)
        stdlib = Path(scratch) / "stdlib"
        env = dict(os.environ, JAIC_STDLIB=str(stdlib))

        def one(module):
            run = subprocess.run([str(jaic), "-doc_model", str(stdlib / module)], capture_output=True, text=True, env=env)
            if run.returncode != 0:
                return []
            try:
                return [(module, item["name"]) for item in json.loads(run.stdout).get("items", [])]
            except ValueError:
                return []

        with ThreadPoolExecutor(max_workers=4) as pool:
            return {pair for pairs in pool.map(one, modules(stdlib)) for pair in pairs}


def generate(jaic, full):
    covered, seen = ([], {}) if full else read(TARGET)
    todo = [t for t in tags() if t not in covered]
    for tag in todo:
        found = items_at(tag, jaic)
        print(f"{tag}: {len(found)} items", file=sys.stderr)
        version = tag[1:] if covered else BASELINE
        for pair in sorted(found):
            seen.setdefault(pair, version)
        covered.append(tag)
    return covered, seen


def check():
    covered, _ = read(TARGET)
    if not covered:
        print(f"{OUTPUTS[0]} has no `# covers:` line", file=sys.stderr)
        return 1
    here = tags()
    if not here:
        return 0
    missing = [t for t in covered if t not in here]
    if missing:
        print(f"{OUTPUTS[0]} covers tags this checkout does not have: {', '.join(missing)}", file=sys.stderr)
        return 1
    if covered != here[: len(covered)]:
        print(f"{OUTPUTS[0]} skips a tag that was released before {covered[-1]}", file=sys.stderr)
        return 1
    if len(here) > len(covered):
        print(f"note: {OUTPUTS[0]} does not cover {', '.join(here[len(covered):])} yet", file=sys.stderr)
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="validate the checked-in file instead of writing it")
    parser.add_argument("--full", action="store_true", help="read every tag again instead of adding the new ones")
    parser.add_argument("--jaic", type=Path, default=cargo_binary("jaic"), help="the compiler to read each release with")
    args = parser.parse_args()
    if args.check:
        try:
            return check()
        except ValueError as problem:
            print(problem, file=sys.stderr)
            return 1
    covered, seen = generate(args.jaic, args.full)
    TARGET.write_text(render(covered, seen), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
