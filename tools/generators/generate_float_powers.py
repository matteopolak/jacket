#!/usr/bin/env python3
"""Emit the 128-bit significands of the powers of five used by decimal to binary float parsing.

Entry q holds 5^q scaled by a power of two into [2^127, 2^128) and rounded down, so every entry
is a lower bound of the exact scaled power. Parsing relies on that direction when it decides
whether its product is close enough to a rounding boundary to need the exact path.
"""

import sys as _sys
from pathlib import Path as _Path

# tools/, for folder-qualified imports
_sys.path.insert(0, str(_Path(__file__).resolve().parents[1]))

from generators.jai_codegen import emit_generated, generator_parser
from toolkit.repo import ROOT

LOWEST = -342
HIGHEST = 308
OUTPUT = ROOT / "stdlib/internal/basic/powers-of-five.jai"


def scaled_floor(q):
    """floor(5^q * 2^k) for the k that puts the result in [2^127, 2^128)."""
    if q >= 0:
        value = 5 ** q
        bits = value.bit_length()
        return value >> (bits - 128) if bits > 128 else value << (128 - bits)
    divisor = 5 ** -q
    # 2^shift / divisor has at least 128 bits; drop the excess, which only rounds down further.
    shift = divisor.bit_length() + 128
    value = (1 << shift) // divisor
    return value >> (value.bit_length() - 128)


def main():
    args = generator_parser(__doc__.split("\n")[0]).parse_args()
    words = []
    for q in range(LOWEST, HIGHEST + 1):
        value = scaled_floor(q)
        assert 1 << 127 <= value < 1 << 128
        words += [value >> 64, value & ((1 << 64) - 1)]
    lines = [", ".join(f"0x{word:016x}" for word in words[i:i + 4]) for i in range(0, len(words), 4)]
    body = ",\n    ".join(lines)
    source = (
        f"// Generated by tools/generators/generate_float_powers.py.\n"
        f"// Two words per power, high then low: 5^q scaled into [2^127, 2^128), rounded down.\n\n"
        f"#scope_module\n"
        f"FIVE_POWER_LOWEST :: {LOWEST};\n"
        f"FIVE_POWER_HIGHEST :: {HIGHEST};\n\n"
        f"FIVE_POWER_WORDS :: u64.[\n    {body}\n];\n"
    )
    emit_generated(OUTPUT, source, args.formatter, args.check)


if __name__ == "__main__":
    main()
